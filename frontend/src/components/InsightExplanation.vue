<template>
  <details>
    <summary>
      Explain this insight
    </summary>

    <div class="explain">
      <p>
        <strong>What this is about:</strong> {{ beginnerContext(insight) }}
      </p>
      <p>
        <strong>Plain language:</strong> {{ plainInsight(insight) }}
      </p>
      <p>
        <strong>Why this score:</strong> {{ scoreNarrative(insight, parts) }}
      </p>

      <ul class="score-parts">
        <li>confidence: {{ parts.confidence }} = {{ fmt(parts.confidenceScore) }}</li>
        <li>source breadth: {{ parts.papers.length }} paper(s) x 0.5 = {{ fmt(parts.paperScore) }}</li>
        <li>reasoning bonus: {{ fmt(parts.realBonus) }}</li>
        <li>total score: {{ fmt(parts.shown) }}</li>
      </ul>

      <button
        type="button"
        class="llm-action"
        :disabled="loading"
        @click="loadLlm"
      >
        {{ loading ? 'Asking LLM...' : 'Ask LLM for more detail' }}
      </button>

      <div
        v-if="error"
        class="muted"
      >
        {{ error }}
      </div>

      <div
        v-else-if="llm"
        class="llm-result"
      >
        <div class="muted">
          Generated by {{ llm.model || 'LLM' }}
        </div>

        <template
          v-for="field in llmFields"
          :key="field.key"
        >
          <h4>{{ field.label }}</h4>
          <p>{{ exp[field.key] }}</p>
        </template>

        <h4>technical terms</h4>
        <p v-if="termsText">
          {{ termsText }}
        </p>
        <dl
          v-else-if="terms.length"
          class="terms"
        >
          <div
            v-for="(t, i) in terms"
            :key="i"
            class="term"
          >
            <dt v-if="t.term">
              {{ t.term }}
            </dt>
            <dd>{{ t.def }}</dd>
          </div>
        </dl>
        <p
          v-else
          class="muted"
        >
          none noted
        </p>
      </div>
    </div>
  </details>
</template>

<script setup>
import { ref, computed } from 'vue'
import { explainInsight } from '../composables/useApi.js'
import {
  fmt,
  scoreBreakdown,
  beginnerContext,
  plainInsight,
  scoreNarrative
} from '../utils/insights.js'

const props = defineProps({
  insight: Object
})

const parts = computed(() => scoreBreakdown(props.insight))

const loading = ref(false)
const error = ref('')
const llm = ref(null)
const exp = computed(() => llm.value?.explanation || {})

// `technical_terms` can come back as a plain string, a {term: explanation} map,
// or a list -- normalise to either a paragraph or a tidy definition list.
const termsText = computed(() =>
  typeof exp.value.technical_terms === 'string' ? exp.value.technical_terms.trim() : '')

const terms = computed(() => {
  const v = exp.value.technical_terms
  if (!v || typeof v === 'string') return []
  const flat = (item) => {
    if (item && typeof item === 'object') {
      return Object.entries(item).map(([term, def]) => ({
        term, def: typeof def === 'string' ? def : JSON.stringify(def)
      }))
    }
    return [{ term: '', def: String(item) }]
  }
  return Array.isArray(v) ? v.flatMap(flat) : flat(v)
})

const llmFields = [
  { key: 'subject', label: 'Subject' },
  { key: 'why_it_matters', label: 'Why It Matters' },
  { key: 'insight', label: 'The Insight' },
  { key: 'evidence', label: 'Evidence' },
  { key: 'contradicting', label: 'Contradicting Evidence' },
  { key: 'caveats', label: 'Caveats' },
  { key: 'full_details', label: 'full details' }
]

async function loadLlm() {
  loading.value = true
  error.value = ''
  llm.value = null
  try {
    const data = await explainInsight(props.insight.id)
    if (data.error) {
      error.value = `LLM explanation unavailable: ${data.error}`
      return
    }
    llm.value = data
    console.log('LLM explanation response:', data.explanation)
  } catch (e) {
    error.value = `LLM explanation failed: ${e}`
  } finally {
    loading.value = false
  }
}
</script>

